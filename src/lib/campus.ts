import type { IssueCategory, Room, RoomType } from '@/src/types/campus';

export const ALL_CATEGORIES: IssueCategory[] = [
  'Lights',
  'Fans',
  'Projectors',
  'Wi-Fi',
  'AC',
  'Plumbing/Washroom',
  'Furniture',
  'Electrical',
  'Cleanliness',
  'Equipment',
  'Other',
];

export function getCategoriesForRoomType(type?: RoomType): IssueCategory[] {
  switch (type) {
    case 'toilet':
      return ['Plumbing/Washroom', 'Cleanliness', 'Lights', 'Electrical', 'Other'];
    case 'lab':
      return [
        'Equipment',
        'Electrical',
        'Wi-Fi',
        'AC',
        'Projectors',
        'Lights',
        'Fans',
        'Furniture',
        'Cleanliness',
        'Other',
      ];
    case 'classroom':
    case 'smart_class':
    case 'seminar_hall':
      return [
        'Projectors',
        'Fans',
        'Lights',
        'Furniture',
        'AC',
        'Wi-Fi',
        'Electrical',
        'Cleanliness',
        'Other',
      ];
    case 'amenity':
    case 'common':
      return [
        'Cleanliness',
        'Lights',
        'Fans',
        'Plumbing/Washroom',
        'Furniture',
        'Wi-Fi',
        'Electrical',
        'Other',
      ];
    default:
      return ALL_CATEGORIES;
  }
}

